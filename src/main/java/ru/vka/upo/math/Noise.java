package ru.vka.upo.math;

import java.util.Random;

/**
 * Ошибки измерений: случайные числа с нормальным законом распределения.
 *
 * <h2>Где это применяется, а где нет</h2>
 *
 * <strong>На числа в таблице результатов этот класс не влияет и в их
 * расчёте не участвует.</strong> Ошибки, которые программа выводит
 * в таблицу, вычисляются аналитически: динамическая – как невязка
 * аппроксимации истинной, безошибочной траектории, случайная – по формуле
 * раздела 4.2 руководства через корреляционную матрицу ошибок оценивания
 * (см. {@link ErrorFormulas}). Никаких случайных чисел там не требуется,
 * поэтому таблица строго воспроизводима: при одних и тех же исходных
 * данных она одна и та же. Так же было устроено и в прежней программе:
 * датчик случайных чисел в ней не применялся вовсе.
 *
 * Настоящий класс обслуживает единственное место программы – показ
 * единичного опыта (класс <code>ru.vka.upo.core.Realization</code>,
 * кнопка «Другая реализация шума» на экране результатов). Там строится
 * одна конкретная реализация процесса измерения, чтобы обучающийся видел,
 * что стоит за словом «случайная»: отсчёты ложатся с разбросом, полином
 * каждый раз проходит немного иначе, а среднее и разброс по накопленным
 * опытам сходятся к тем самым ERD и ERS, которые уже напечатаны в таблице.
 * Меняются при этом только график измерений и подпись под графиками.
 *
 * <h2>Что именно моделируется</h2>
 *
 * Ошибка каждого отдельного измерения принимается нормальной, с нулевым
 * средним и заданным средним квадратическим отклонением, а ошибки разных
 * измерений – независимыми. Это и есть стационарность ошибки измерения:
 * закон распределения один и тот же в любой момент времени, и от того,
 * когда измерение сделано, он не зависит.
 *
 * Стационарность относится именно к ошибке отдельного измерения. Ошибка
 * <em>оценки</em>, получаемой сглаживанием, постоянной по интервалу
 * усреднения не будет: оценка есть взвешенная сумма всех измерений
 * выборки, а веса зависят от того, к какому моменту оценка отнесена –
 * см. {@link ErrorFormulas}.
 *
 * <h2>Повторяемость</h2>
 *
 * Числа берутся у стандартного датчика псевдослучайных чисел, приведённого
 * к нормальному закону преобразованием Марсальи-Брея (метод nextGaussian
 * стандартной библиотеки). Датчик запускается с заданного зерна, поэтому
 * при одном и том же зерне последовательность одна и та же: расчёт
 * воспроизводим, и один и тот же опыт можно показать дважды. Чтобы
 * получить другую реализацию шума при тех же условиях, достаточно сменить
 * зерно.
 *
 * <h2>Как это проверить</h2>
 *
 * Достаточно набрать длинную последовательность и убедиться, что её
 * среднее близко к нулю, а среднее квадратическое отклонение – к заданному
 * (для выборки из 10000 чисел отклонение того и другого составляет доли
 * процента), а также что при одинаковом зерне последовательности совпадают
 * полностью.
 */
public final class Noise {

    private Noise() {
    }

    /**
     * Последовательность ошибок измерений для показа единичного опыта.
     * В расчёте таблицы результатов не используется.
     *
     * @param count число измерений
     * @param sigma среднее квадратическое отклонение ошибки измерения
     * @param seed  зерно датчика: при одном и том же зерне числа те же
     */
    public static double[] sample(int count, double sigma, long seed) {
        Random rnd = new Random(seed);
        double[] out = new double[count];
        for (int i = 0; i < count; i++) {
            out[i] = sigma * rnd.nextGaussian();
        }
        return out;
    }
}
