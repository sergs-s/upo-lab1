package ru.vka.upo.math;

/**
 * Вычисление значения полинома и его производной.
 *
 * Полином задан коэффициентами при степенях нормированного времени:
 *
 * <pre>
 *     p(x) = c₀ + c₁·x + c₂·x² + … + c_m·x^m,     x = (t − t₀)/L.
 * </pre>
 *
 * Значение считается по схеме Горнера: начиная со старшего коэффициента,
 * результат умножается на x и к нему прибавляется следующий коэффициент.
 * Схема требует ровно m умножений и m сложений вместо возведения в степень
 * на каждом слагаемом и при этом устойчивее: промежуточные величины
 * не разрастаются, а значит, не теряются младшие разряды.
 *
 * Производная по нормированному времени считается той же схемой по
 * коэффициентам j·c_j. Чтобы получить производную по обычному времени
 * (то есть скорость изменения параметра), её надо разделить на масштаб L.
 *
 * Все методы продублированы для одинарной точности: они нужны для
 * воспроизведения прежней программы, которая хранила и вычитала дальности
 * числами одинарной точности. При дальности порядка миллиона метров такое
 * округление само по себе даёт разброс в доли метра, и без него «полка»
 * прежней программы не воспроизводится.
 *
 * Проверить класс просто: значение полинома в нескольких точках сравнить
 * с прямым подсчётом по определению, а производную – с разностным
 * отношением при малом приращении.
 */
public final class Polynomial {

    private Polynomial() {
    }

    /**
     * Значение полинома в точке x (двойная точность).
     *
     * @param c коэффициенты, начиная со свободного члена
     * @param x нормированное время
     */
    public static double value(double[] c, double x) {
        double p = 0;
        for (int j = c.length - 1; j >= 0; j--) {
            p = p * x + c[j];
        }
        return p;
    }

    /**
     * Производная полинома по нормированному времени в точке x
     * (двойная точность). Чтобы перейти к производной по обычному времени,
     * результат делится на масштаб нормировки.
     */
    public static double derivative(double[] c, double x) {
        double dp = 0;
        for (int j = c.length - 1; j >= 1; j--) {
            dp = dp * x + j * c[j];
        }
        return dp;
    }

    /**
     * Значение полинома в одинарной точности: и сами коэффициенты,
     * и аргумент, и все промежуточные величины округляются до float,
     * как это было в прежней программе.
     */
    public static float valueSingle(double[] c, double x) {
        float fx = (float) x;
        float p = 0f;
        for (int j = c.length - 1; j >= 0; j--) {
            p = p * fx + (float) c[j];
        }
        return p;
    }

    /** Производная полинома по нормированному времени в одинарной точности. */
    public static float derivativeSingle(double[] c, double x) {
        float fx = (float) x;
        float dp = 0f;
        for (int j = c.length - 1; j >= 1; j--) {
            dp = dp * fx + j * (float) c[j];
        }
        return dp;
    }
}
