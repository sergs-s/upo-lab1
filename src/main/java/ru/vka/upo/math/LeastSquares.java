package ru.vka.upo.math;

/**
 * Взвешенный метод наименьших квадратов с полиномиальным базисом.
 *
 * <h2>Что решается</h2>
 *
 * Измерения y<sub>i</sub>, снятые в моменты t<sub>i</sub>, приближаются
 * полиномом степени m относительно момента привязки t<sub>0</sub>:
 *
 * <pre>
 *     r̂(t) = α₀ + α₁·x + α₂·x² + … + α_m·x^m,   x = (t − t₀)/L,
 * </pre>
 *
 * где L – масштаб нормировки времени (половина интервала усреднения).
 * Коэффициенты α находятся из условия наименьшей суммы квадратов
 * взвешенных отклонений:
 *
 * <pre>
 *     Σ w_i²·(y_i − r̂(t_i))² → min,     w_i = 1/σ_i.
 * </pre>
 *
 * В матричной записи это A·α ≈ b, где строка матрицы A есть вектор степеней
 * нормированного времени, умноженный на вес измерения, а b – взвешенные
 * измерения. Формальное решение α = (AᵀA)⁻¹Aᵀb, а корреляционная матрица
 * ошибок оценок коэффициентов K<sub>α</sub> = σ²(AᵀA)⁻¹ – именно та, которую
 * выписывает руководство к работе в разделе 4.2.
 *
 * <h2>Почему не обращается матрица нормальных уравнений</h2>
 *
 * Матрица AᵀA при полиномиальном базисе обусловлена крайне плохо: её
 * элементы суть суммы степеней времени, и при росте степени полинома они
 * различаются на многие порядки. Прямое составление и обращение такой
 * матрицы (именно так делала прежняя программа – см. {@link NormalEquations})
 * теряет значащие цифры, и при степени 2 и выше результат определяется уже
 * не формулой, а разрядностью машинных чисел.
 *
 * Здесь вместо этого выполняется ортогональное разложение Хаусхолдера
 * A = Q·R, где Q ортогональна (QᵀQ = E), а R верхнетреугольная. Тогда
 *
 * <pre>
 *     α = R⁻¹·Qᵀ·b,     (AᵀA)⁻¹ = R⁻¹·R⁻ᵀ,
 * </pre>
 *
 * то есть ни AᵀA, ни её обращение вообще не вычисляются. Число
 * обусловленности задачи при этом равно обусловленности самой A, а не её
 * квадрату, и точность сохраняется при любой степени полинома,
 * предусмотренной заданием.
 *
 * <h2>Нормировка времени</h2>
 *
 * Дополнительно время нормируется на половину интервала усреднения, так что
 * аргумент полинома лежит в пределах от минус единицы до единицы. Это ещё
 * на несколько порядков улучшает обусловленность: без нормировки при шаге
 * 0,01 с и выборке 49 измерений аргумент меняется от 0 до 0,48, и его
 * четвёртая степень уже мала настолько, что теряется в сумме.
 *
 * <h2>Как это проверить</h2>
 *
 * Класс работает только с числами: ни исходных данных работы, ни модели
 * движения он не знает. Поэтому его можно проверить отдельно на любом
 * примере с известным ответом – например, задав измерения точно на полиноме
 * (тогда коэффициенты обязаны получиться теми же с точностью до машинного
 * нуля) или сравнив K<sub>α</sub> с обращением AᵀA, посчитанным независимо
 * для малых степеней, где такое обращение ещё достоверно.
 */
public class LeastSquares {

    /** Число строк матрицы A: столько всего измерений в выборке. */
    private final int rows;
    /** Число столбцов матрицы A: m + 1 коэффициент полинома. */
    private final int cols;
    /** Взвешенная матрица A. */
    private final double[][] a;
    /** Масштаб нормировки времени L, с. */
    private final double scale;
    /** Верхнетреугольная матрица R разложения A = Q·R. */
    private double[][] r;
    /** Матрица Qᵀ того же разложения. */
    private double[][] qt;

    private LeastSquares(int rows, int cols, double timeScale) {
        this.rows = rows;
        this.cols = cols;
        this.a = new double[rows][cols];
        this.scale = timeScale;
    }

    /**
     * Создаёт задачу МНК для полиномиального усреднения и сразу выполняет
     * разложение матрицы: дальше по одному и тому же разложению можно
     * решать систему с разными правыми частями и получать корреляционную
     * матрицу, не повторяя вычислений.
     *
     * Строка матрицы для измерения дальности есть вектор степеней
     * нормированного времени (1, x, x², …, x^m). Строка для измерения
     * радиальной скорости есть производная того же полинома по времени:
     * (0, 1/L, 2x/L, …, m·x^(m−1)/L) – скорость измеряется тем же
     * измерителем, а связана с теми же коэффициентами через производную,
     * поэтому оба вида измерений входят в одну систему.
     *
     * @param s         относительное время каждого измерения, с (отсчёт от привязки)
     * @param velocity  признак того, что измерение относится к радиальной скорости
     * @param weight    вес измерения (единица, делённая на СКО измерения)
     * @param degree    степень аппроксимирующего полинома m
     * @param timeScale масштаб нормировки времени L, с
     */
    public static LeastSquares forPolynomial(double[] s, boolean[] velocity,
            double[] weight, int degree, double timeScale) {
        int n = s.length;
        int p = degree + 1;
        LeastSquares l = new LeastSquares(n, p, timeScale);
        for (int i = 0; i < n; i++) {
            double x = s[i] / timeScale;
            for (int j = 0; j < p; j++) {
                double v;
                if (!velocity[i]) {
                    v = Math.pow(x, j);
                } else {
                    // производная j-й степени по времени: j·x^(j−1)·dx/dt,
                    // а dx/dt = 1/L, отсюда деление на масштаб
                    v = j == 0 ? 0.0 : j * Math.pow(x, j - 1) / timeScale;
                }
                l.a[i][j] = v * weight[i];
            }
        }
        l.decompose();
        return l;
    }

    /**
     * Разложение Хаусхолдера A = Q·R.
     *
     * На каждом шаге k строится отражение относительно гиперплоскости,
     * обнуляющее поддиагональные элементы k-го столбца. Отражение задаётся
     * вектором v и действует как H = E − 2vvᵀ/(vᵀv); применение такого
     * отражения к матрице сводится к вычитанию, то есть выполняется без
     * деления на малые числа и потому численно устойчиво. Последовательное
     * применение отражений превращает A в верхнетреугольную R, а их
     * произведение даёт Qᵀ.
     */
    private void decompose() {
        double[][] m = new double[rows][cols];
        for (int i = 0; i < rows; i++) {
            System.arraycopy(a[i], 0, m[i], 0, cols);
        }
        double[][] q = identity(rows);

        for (int k = 0; k < cols; k++) {
            double norm = 0;
            for (int i = k; i < rows; i++) {
                norm += m[i][k] * m[i][k];
            }
            norm = Math.sqrt(norm);
            if (norm == 0) {
                // столбец уже нулевой: отражать нечего
                continue;
            }
            // знак выбирается так, чтобы при вычитании не пропали значащие
            // цифры: вычитается величина, заведомо не близкая к нулю
            if (m[k][k] > 0) {
                norm = -norm;
            }
            double[] v = new double[rows];
            for (int i = k; i < rows; i++) {
                v[i] = m[i][k];
            }
            v[k] -= norm;
            double vv = 0;
            for (int i = k; i < rows; i++) {
                vv += v[i] * v[i];
            }
            if (vv == 0) {
                continue;
            }
            // применяем отражение к m и накапливаем его в q
            for (int j = k; j < cols; j++) {
                double dot = 0;
                for (int i = k; i < rows; i++) {
                    dot += v[i] * m[i][j];
                }
                double f = 2 * dot / vv;
                for (int i = k; i < rows; i++) {
                    m[i][j] -= f * v[i];
                }
            }
            for (int j = 0; j < rows; j++) {
                double dot = 0;
                for (int i = k; i < rows; i++) {
                    dot += v[i] * q[i][j];
                }
                double f = 2 * dot / vv;
                for (int i = k; i < rows; i++) {
                    q[i][j] -= f * v[i];
                }
            }
        }
        this.r = m;
        this.qt = q;
    }

    /** Единичная матрица порядка n. */
    private static double[][] identity(int n) {
        double[][] e = new double[n][n];
        for (int i = 0; i < n; i++) {
            e[i][i] = 1.0;
        }
        return e;
    }

    /**
     * Оценки коэффициентов полинома по вектору измерений: α = R⁻¹·Qᵀ·b.
     *
     * Возвращаются коэффициенты при степенях нормированного времени;
     * чтобы получить коэффициент при обычном времени, j-й коэффициент
     * надо разделить на L в j-й степени. Нулевой коэффициент – это сама
     * оценка параметра в момент привязки, первый, делённый на L, – оценка
     * скорости его изменения.
     */
    public double[] solve(double[] measurements, double[] weight) {
        double[] b = new double[rows];
        for (int i = 0; i < rows; i++) {
            b[i] = measurements[i] * weight[i];
        }
        double[] qtb = new double[rows];
        for (int i = 0; i < rows; i++) {
            double sum = 0;
            for (int j = 0; j < rows; j++) {
                sum += qt[i][j] * b[j];
            }
            qtb[i] = sum;
        }
        return backSubstitute(qtb);
    }

    /** Обратный ход: решение верхнетреугольной системы R·α = y. */
    private double[] backSubstitute(double[] y) {
        double[] c = new double[cols];
        for (int i = cols - 1; i >= 0; i--) {
            double sum = y[i];
            for (int j = i + 1; j < cols; j++) {
                sum -= r[i][j] * c[j];
            }
            c[i] = sum / r[i][i];
        }
        return c;
    }

    /**
     * Корреляционная матрица ошибок оценивания коэффициентов при
     * нормированном времени: K = (AᵀA)⁻¹ = R⁻¹·R⁻ᵀ.
     *
     * Веса измерений уже входят в A, поэтому дисперсия измерения в матрице
     * не появляется: K[0][0] есть дисперсия оценки параметра в момент
     * привязки, K[1][1], делённая на квадрат масштаба, – дисперсия оценки
     * скорости. Это и есть та матрица K<sub>α</sub> из раздела 4.2
     * руководства, у которой σ<sub>δr</sub>² вынесено в веса.
     *
     * Сначала обращается треугольная матрица R (обратный ход по столбцам),
     * затем перемножаются R⁻¹ и R⁻ᵀ. Обе операции точные в том смысле,
     * что не требуют вычисления AᵀA.
     */
    public double[][] covariance() {
        double[][] inv = new double[cols][cols]; // R в минус первой степени
        for (int j = 0; j < cols; j++) {
            inv[j][j] = 1.0 / r[j][j];
            for (int i = j - 1; i >= 0; i--) {
                double sum = 0;
                for (int k = i + 1; k <= j; k++) {
                    sum += r[i][k] * inv[k][j];
                }
                inv[i][j] = -sum / r[i][i];
            }
        }
        double[][] k = new double[cols][cols];
        for (int i = 0; i < cols; i++) {
            for (int j = 0; j < cols; j++) {
                double sum = 0;
                for (int t = Math.max(i, j); t < cols; t++) {
                    sum += inv[i][t] * inv[j][t];
                }
                k[i][j] = sum;
            }
        }
        return k;
    }

    /**
     * Среднее квадратическое отклонение оценки параметра, отнесённой
     * к произвольному моменту времени: σ(t) = √(aᵀ(t)·K·a(t)), где
     * a(t) – вектор степеней нормированного времени.
     *
     * Именно эта величина и объясняет, почему случайная ошибка не постоянна
     * по интервалу усреднения: при m = 0 вектор a вырождается в единицу
     * и σ = σ<sub>изм</sub>/√N при любом t, а при большей степени σ(t) есть
     * квадратичная форма, наименьшая вблизи середины выборки и быстро
     * растущая за её пределами.
     *
     * @param s время относительно момента привязки, с
     */
    public double sigmaAt(double s) {
        return ErrorFormulas.sigma(covariance(), s / scale);
    }

    /** Масштаб нормировки времени L, с. */
    public double timeScale() {
        return scale;
    }

    /** Степень аппроксимирующего полинома m. */
    public int degree() {
        return cols - 1;
    }
}
