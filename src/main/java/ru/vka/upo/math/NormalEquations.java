package ru.vka.upo.math;

/**
 * Решение задачи наименьших квадратов так, как это делала прежняя
 * фортрановская программа: составлением матрицы нормальных уравнений
 * A<sup>T</sup>A и прямым её обращением, причём всё в одинарной точности.
 *
 * <h2>Зачем это сохранено</h2>
 *
 * Этот способ намеренно оставлен неисправленным: он нужен, чтобы показать,
 * откуда в прежней программе бралась «полка» – уровень, ниже которого
 * динамическая ошибка не опускалась, сколько ни повышай степень полинома.
 * Пользоваться им для расчёта не следует, правильный путь – ортогональное
 * разложение, см. {@link LeastSquares}.
 *
 * <h2>Отчего теряется точность</h2>
 *
 * Матрица AᵀA есть матрица сумм степеней времени (матрица Гильбертова
 * типа). Её число обусловленности равно квадрату числа обусловленности
 * самой A и при степени полинома 4 доходит до десяти в восьмой степени
 * и более. В одинарной точности мантисса вмещает около семи десятичных
 * цифр, поэтому при обращении такой матрицы значащие цифры пропадают
 * целиком, и в ответе остаётся собственная погрешность вычислений.
 *
 * Именно поэтому в прежней программе при m = 2 и выше динамическая ошибка
 * переставала зависеть от параметров режима: выводилась уже не ошибка
 * аппроксимации, а шум округления. То, что это шум, а не свойство метода,
 * видно из сравнения: та же формула, посчитанная в двойной точности,
 * продолжает убывать с ростом степени.
 *
 * <h2>Как это проверить</h2>
 *
 * Достаточно посчитать одну и ту же выборку этим классом и классом
 * {@link LeastSquares}: при m = 0 и m = 1 результаты совпадут, при m = 2
 * и выше разойдутся, причём здешний результат перестанет меняться
 * при изменении шага измерений – признак того, что считается уже
 * не аппроксимация.
 */
public final class NormalEquations {

    private NormalEquations() {
    }

    /**
     * Оценки коэффициентов полинома в одинарной точности.
     *
     * Порядок действий в точности тот же, что и в прежней программе:
     * <ol>
     *   <li>строится матрица степеней нормированного времени, все числа
     *       одинарной точности;</li>
     *   <li>накапливаются AᵀA и Aᵀy;</li>
     *   <li>матрица AᵀA обращается методом Гаусса-Жордана с приведением
     *       строки к единице, без выбора главного элемента – как и было
     *       в прежней программе;</li>
     *   <li>коэффициенты получаются умножением обратной матрицы на Aᵀy.</li>
     * </ol>
     *
     * Веса измерений здесь не применяются: прежняя программа обрабатывала
     * измерения дальности как равноточные.
     *
     * @param s     относительное время каждого измерения, с (отсчёт от базиса)
     * @param truth значения измеряемого параметра
     * @param m     степень аппроксимирующего полинома
     * @param scale масштаб нормировки времени, с
     * @return коэффициенты при степенях нормированного времени – в том же
     *         виде, в каком их выдаёт {@link LeastSquares#solve}
     */
    public static double[] solve(double[] s, double[] truth, int m, double scale) {
        int n = s.length;
        int k = m + 1;
        float[][] a = new float[n][k];
        for (int i = 0; i < n; i++) {
            float x = (float) (s[i] / scale);
            float p = 1f;
            for (int j = 0; j < k; j++) {
                if (j > 0) {
                    p *= x;
                }
                a[i][j] = p;
            }
        }
        float[][] ata = new float[k][k];
        float[] aty = new float[k];
        for (int i = 0; i < n; i++) {
            float y = (float) truth[i];
            for (int p = 0; p < k; p++) {
                aty[p] += a[i][p] * y;
                for (int q = 0; q < k; q++) {
                    ata[p][q] += a[i][p] * a[i][q];
                }
            }
        }
        float[][] inv = new float[k][k];
        for (int i = 0; i < k; i++) {
            inv[i][i] = 1f;
        }
        for (int c = 0; c < k; c++) {
            float diag = ata[c][c];
            if (diag == 0f) {
                continue;
            }
            for (int j = 0; j < k; j++) {
                ata[c][j] /= diag;
                inv[c][j] /= diag;
            }
            for (int r = 0; r < k; r++) {
                if (r == c) {
                    continue;
                }
                float f = ata[r][c];
                for (int j = 0; j < k; j++) {
                    ata[r][j] -= f * ata[c][j];
                    inv[r][j] -= f * inv[c][j];
                }
            }
        }
        double[] out = new double[k];
        for (int p = 0; p < k; p++) {
            float v = 0;
            for (int q = 0; q < k; q++) {
                v += inv[p][q] * aty[q];
            }
            out[p] = v;
        }
        return out;
    }
}
