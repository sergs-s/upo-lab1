/**
 * Математика лабораторной работы, собранная отдельно от программы.
 *
 * <h2>Зачем выделен этот пакет</h2>
 *
 * Всё, что считается в работе, лежит здесь и нигде больше. Классы пакета
 * не знают ни об экранах программы, ни о рабочей тетради, ни о файле
 * исходных данных: на вход подаются числа и массивы чисел, на выходе
 * получаются числа. Благодаря этому любую формулу можно проверить
 * отдельно – хоть ручным расчётом, хоть сторонней программой, – не
 * запуская саму лабораторную работу и не разбираясь в её устройстве.
 *
 * Остальные пакеты программы этой математики не дублируют: расчётное ядро
 * {@link ru.vka.upo.core} лишь собирает исходные данные в массивы, вызывает
 * здешние формулы и раскладывает результат по строкам таблицы.
 *
 * <h2>Что где лежит</h2>
 *
 * <ul>
 *   <li>{@link ru.vka.upo.math.LeastSquares} – взвешенный метод наименьших
 *       квадратов с полиномиальным базисом: ортогональное разложение,
 *       оценки коэффициентов, корреляционная матрица ошибок оценок;</li>
 *   <li>{@link ru.vka.upo.math.NormalEquations} – тот же метод, но так,
 *       как его считала прежняя программа: нормальные уравнения с прямым
 *       обращением матрицы в одинарной точности. Оставлено намеренно,
 *       чтобы было видно происхождение «полки»;</li>
 *   <li>{@link ru.vka.upo.math.ErrorFormulas} – формулы ошибок из раздела
 *       4.2 руководства: случайная ошибка в произвольный момент, полная
 *       ошибка, а также средняя невязка аппроксимации, которую прежняя
 *       программа принимала за динамическую ошибку;</li>
 *   <li>{@link ru.vka.upo.math.Polynomial} – значение полинома и его
 *       производной по схеме Горнера, в двойной и в одинарной точности;</li>
 *   <li>{@link ru.vka.upo.math.Geometry} – формулы дальности и радиальной
 *       скорости для обеих обстановок, предусмотренных руководством;</li>
 *   <li>{@link ru.vka.upo.math.SampleWindows} – разметка выборок по
 *       интервалу измерений, наша и восстановленная разметка прежней
 *       программы со всеми её особенностями;</li>
 *   <li>{@link ru.vka.upo.math.Noise} – нормальный шум с заданным СКО,
 *       нужный только для показа единичного опыта; в расчёте таблицы
 *       результатов не участвует.</li>
 * </ul>
 *
 * <h2>Откуда берутся ошибки, выводимые в таблицу</h2>
 *
 * Расчёт работы целиком аналитический, и так же он был устроен в прежней
 * программе: датчик случайных чисел в ней не применялся вовсе, что
 * установлено опытом (при удвоении СКО измерения динамическая ошибка
 * не изменилась ни в одном разряде, а случайная выросла ровно вдвое).
 * Динамическая ошибка есть невязка аппроксимации истинной, безошибочной
 * траектории полиномом; случайная ошибка есть значение формулы
 * σ<sub>δr</sub>·√(aᵀ(t)(AᵀA)⁻¹a(t)); полная – их сложение по квадратам.
 * Поэтому таблица результатов от какой бы то ни было реализации шума
 * не зависит и при повторении расчёта воспроизводится в точности.
 *
 * Шум как таковой появляется в программе лишь на иллюстрации единичного
 * опыта, которой в прежней программе не было: она показывает, что среднее
 * и разброс по многим опытам сходятся к тем самым числам, которые
 * в таблице уже стоят.
 *
 * <h2>Как проверить</h2>
 *
 * В каждом классе описано, что именно и каким образом в нём проверяется.
 * Готовый набор таких проверок собран в классе
 * <code>ru.vka.upo.math.MathCheck</code> (папка src/test): он сверяет
 * оценки МНК с заведомо известными ответами, корреляционную матрицу –
 * с независимым расчётом, случайную ошибку – с формулой σ/√N при нулевой
 * степени полинома, производные – с разностными отношениями, разметку
 * выборок – с прямым счётом, а формулы дальности – с теоремой косинусов.
 * Проверки печатают, что сошлось и с какой разницей, и запускаются
 * отдельно от программы.
 */
package ru.vka.upo.math;
