package ru.vka.upo.math;

/**
 * Разметка выборок по интервалу измерений: в какие моменты начинаются
 * те пять выборок, для которых выводится таблица ошибок.
 *
 * Предусмотрены два способа разметки.
 *
 * <h2>Равномерный (наш)</h2>
 *
 * Выборки расставляются так, чтобы каждая целиком лежала внутри интервала
 * измерений: первая начинается в его начале, последняя им заканчивается,
 * остальные распределены между ними поровну. При длине выборки
 * T<sub>у</sub> = (N−1)Δt последняя начинается в момент T<sub>К</sub> − T<sub>у</sub>,
 * а k-я – в доле k/(ROWS−1) от этого значения.
 *
 * <h2>Как размечала прежняя программа</h2>
 *
 * Прежняя программа отсчитывала начало k-й выборки не по времени,
 * а по номеру измерения, и делала это так:
 *
 * <ol>
 *   <li>шаг между началами выборок в измерениях есть целая часть
 *       T<sub>К</sub>/5/Δt, причём шаг измерений Δt хранился числом
 *       одинарной точности, а деление выполнялось в двойной. Из-за этого,
 *       например, при T<sub>К</sub> = 180 с и Δt = 0,1 с получается
 *       180/5/0,1 = 359,999994, целая часть которого 359, а не 360:
 *       выборки идут через 35,9 с вместо 36 с;</li>
 *   <li>сам момент набирается повторным прибавлением шага Δt в одинарной
 *       точности, отчего накапливается снос: при Δt = 0,01 с и 18000
 *       прибавлениях последняя выборка начинается в 179,98 с;</li>
 *   <li>выборку, не укладывающуюся в запас 1,2·T<sub>К</sub>, программа
 *       не считала вовсе – поэтому при больших N в её таблице пять строк
 *       превращаются в четыре.</li>
 * </ol>
 *
 * Всё это восстановлено по прогонам самой прежней программы и проверено
 * на 20 сочетаниях T<sub>К</sub>, Δt, N и M0 без расхождений. Здесь оно
 * воспроизведено намеренно: иначе таблицы новой программы нельзя было бы
 * сопоставить с прежними расчётами построчно.
 *
 * Проверить разметку можно прямым счётом: при T<sub>К</sub> = 180 с,
 * Δt = 0,1 с способ прежней программы обязан дать 35,9; 71,8; 107,7; 143,6
 * и 179,5 с, а равномерный при N = 49 – 0; 33; 66; 99 и 132 с.
 */
public final class SampleWindows {

    private SampleWindows() {
    }

    /**
     * Равномерная разметка: каждая выборка целиком внутри интервала
     * измерений.
     *
     * @param interval интервал измерений T<sub>К</sub>, с
     * @param sampleSize объём выборки N, измерений
     * @param step шаг измерений Δt, с
     * @param rows число выборок (строк таблицы)
     */
    public static double[] uniform(double interval, int sampleSize, double step,
            int rows) {
        double[] starts = new double[rows];
        double length = (sampleSize - 1) * step;
        double last = Math.max(interval - length, 0.0);
        for (int k = 0; k < rows; k++) {
            starts[k] = last * k / (rows - 1.0);
        }
        return starts;
    }

    /**
     * Разметка прежней программы: по номерам измерений, с накоплением
     * шага в одинарной точности.
     *
     * @param interval интервал измерений T<sub>К</sub>, с
     * @param step шаг измерений Δt, с
     * @param rows число выборок (строк таблицы)
     */
    public static double[] legacy(double interval, double step, int rows) {
        double[] starts = new double[rows];
        float singleStep = (float) step;
        // деление ведётся в двойной точности, а шаг взят одинарной:
        // именно это сочетание и даёт 359 вместо 360 при Δt = 0,1 с
        int perWindow = (int) (interval / rows / (double) singleStep);
        float time = 0f;
        int made = 0;
        for (int k = 1; k <= rows; k++) {
            while (made < k * perWindow) {
                time += singleStep;
                made++;
            }
            starts[k - 1] = time;
        }
        return starts;
    }

    /**
     * Укладывается ли выборка в запас, за которым прежняя программа её
     * уже не считала. Запас составляет 1,2 интервала измерений и
     * отсчитывается по полной длине выборки N·Δt (не (N−1)Δt) – так это
     * определено в самой прежней программе.
     */
    public static boolean fitsLegacyLimit(double windowStart, double interval,
            int sampleSize, double step) {
        double limit = 1.2 * interval;
        double span = sampleSize * step;
        return windowStart + span <= limit + 1e-9;
    }

    /**
     * Момент привязки внутри выборки в отсчёте прежней программы:
     * начало выборки плюс (M0 − 1) шагов, набранных повторным сложением
     * в одинарной точности.
     *
     * При мелком шаге это заметно отличается от произведения: например,
     * при Δt = 0,01 с и M0 = 25 накопление даёт не ровно 0,24 с. Разница
     * невелика, но в таблицу моментов времени она входит, и без неё
     * построчное сравнение с прежней программой не сходится.
     */
    public static double legacyAnchorTime(double windowStart, double step, int anchor) {
        float acc = (float) windowStart;
        float singleStep = (float) step;
        for (int i = 1; i < anchor; i++) {
            acc += singleStep;
        }
        return acc;
    }

    /**
     * Момент привязки внутри выборки в обычном отсчёте: начало выборки
     * плюс (M0 − 1) шагов, посчитанных умножением в двойной точности.
     */
    public static double anchorTime(double windowStart, double step, int anchor) {
        return windowStart + (anchor - 1) * step;
    }
}
