package ru.vka.upo.math;

/**
 * Формулы ошибок оценивания, выписанные в руководстве к работе
 * (раздел 4.2), в отдельном виде: только числа на входе и на выходе.
 *
 * <h2>Две составляющие и их сложение</h2>
 *
 * Полная ошибка оценки складывается из двух: динамической и случайной.
 *
 * <pre>
 *     E_i² = Δ_i² + σ_i²,
 * </pre>
 *
 * где Δ_i – динамическая ошибка, то есть разность между истинным значением
 * параметра и значением аппроксимирующей функции <em>в i-й момент
 * времени</em>, а σ_i² – дисперсия ошибки оценивания параметра <em>в этот
 * же момент</em>, то есть i-й диагональный элемент корреляционной матрицы
 * ошибок K<sub>r</sub>.
 *
 * Существенно, что обе величины отнесены к одному и тому же моменту
 * времени. Складывать квадрат средней невязки аппроксимации по всему
 * интервалу усреднения с квадратом точечной случайной ошибки нельзя: это
 * разные по смыслу величины, и такая сумма ничему в теории не отвечает.
 * Именно так поступала прежняя программа, и для сопоставления с ней этот
 * способ сохранён в {@link #rms(double[])} – но пользоваться им как
 * определением динамической ошибки не следует.
 *
 * <h2>Случайная ошибка в произвольный момент</h2>
 *
 * Оценка параметра в момент t есть r̂(t) = aᵀ(t)·α̂, где a(t) – вектор
 * степеней нормированного времени. Отсюда её дисперсия
 *
 * <pre>
 *     σ²(t) = aᵀ(t)·Kα·a(t)
 * </pre>
 *
 * то есть квадратичная форма от вектора a(t), а не постоянная величина.
 * Постоянной она становится ровно в одном случае – при степени полинома
 * ноль, когда вектор a вырождается в единицу и остаётся σ<sub>изм</sub>/√N.
 * Во всех прочих случаях случайная ошибка зависит от того, к какому моменту
 * отнесена оценка: она наименьшая вблизи середины выборки и быстро растёт
 * за её пределами.
 *
 * <h2>Как это проверить</h2>
 *
 * При m = 0 функция {@link #sigma(double[][], double)} обязана дать одно
 * и то же число при любом x, и это число, умноженное на СКО измерения,
 * равно σ<sub>изм</sub>/√N. При m ≥ 1 значение в середине выборки должно
 * быть наименьшим, а при удалении от неё – расти; профиль симметричен
 * относительно середины, если выборка расположена симметрично.
 */
public final class ErrorFormulas {

    private ErrorFormulas() {
    }

    /**
     * Среднее квадратическое отклонение оценки параметра, отнесённой
     * к моменту с нормированным временем x: σ(x) = √(aᵀ(x)·K·a(x)).
     *
     * Степени нормированного времени накапливаются последовательным
     * умножением, а не возведением в степень: так меньше действий и
     * не теряются младшие разряды при больших степенях.
     *
     * @param covariance корреляционная матрица ошибок оценок коэффициентов
     * @param x          нормированное время (t − t₀)/L
     */
    public static double sigma(double[][] covariance, double x) {
        int k = covariance.length;
        double[] a = new double[k];
        a[0] = 1.0;
        for (int j = 1; j < k; j++) {
            a[j] = a[j - 1] * x;
        }
        double v = 0;
        for (int i = 0; i < k; i++) {
            for (int j = 0; j < k; j++) {
                v += a[i] * covariance[i][j] * a[j];
            }
        }
        return Math.sqrt(Math.max(v, 0.0));
    }

    /**
     * Полная ошибка по её двум составляющим: E = √(Δ² + σ²).
     *
     * Если одна из составляющих не определена (например, оценки скорости
     * нет при полиноме нулевой степени), результат тоже не определён.
     */
    public static double total(double dynamic, double random) {
        if (Double.isNaN(dynamic) || Double.isNaN(random)) {
            return Double.NaN;
        }
        return Math.sqrt(dynamic * dynamic + random * random);
    }

    /**
     * Средняя квадратическая невязка аппроксимации по выборке:
     * √(Σ Δ_i²/N).
     *
     * Так вычисляла «динамическую ошибку» прежняя программа. Это не
     * точечная ошибка в момент привязки, а мера того, насколько хорошо
     * полином описывает выборку в целом, и от момента привязки она
     * не зависит вовсе. Метод оставлен для воспроизведения прежних
     * расчётов и для наглядного сравнения двух определений.
     *
     * @param residuals невязки в каждом измерении выборки
     */
    public static double rms(double[] residuals) {
        double sum = 0;
        for (double d : residuals) {
            sum += d * d;
        }
        return Math.sqrt(sum / residuals.length);
    }
}
